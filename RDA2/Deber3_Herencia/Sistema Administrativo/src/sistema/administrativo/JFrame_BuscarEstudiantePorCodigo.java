    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        String codigo = campoCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Estudiante estudianteEncontrado = SistemaAdministrativo.buscarEstudiantePorCodigo(codigo, listaEstudiantes);

        if (estudianteEncontrado == null) {
            limpiarTabla();
            JOptionPane.showMessageDialog(this, "No existe un estudiante con el código " + codigo + ".", "Aviso", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        mostrarDatosEstudiante(estudianteEncontrado);
    }//GEN-LAST:event_botonBuscarActionPerformed

    private void limpiarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaDatosEstudiantes.getModel();
        modelo.setRowCount(0);
    }

    private void mostrarDatosEstudiante(Estudiante estudiante) {
        limpiarTabla();
        DefaultTableModel modelo = (DefaultTableModel) tablaDatosEstudiantes.getModel();
        modelo.addRow(new Object[]{"Nombre", estudiante.getNombre() + " " + estudiante.getApellido()});
        modelo.addRow(new Object[]{"Cédula", estudiante.getCedula()});
        modelo.addRow(new Object[]{"Correo", estudiante.getCorreo()});
        modelo.addRow(new Object[]{"Teléfono", estudiante.getTelefono()});
        modelo.addRow(new Object[]{"Carrera", estudiante.getCarrera()});
        modelo.addRow(new Object[]{"Nivel", estudiante.getNivel()});
        modelo.addRow(new Object[]{"Código", estudiante.getCodigo()});
    }

