    private void botonRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonRegistrarActionPerformed
        // TODO add your handling code here:

        String nombres = campoNombres.getText().trim();
        String apellidos = campoApellidos.getText().trim();
        String cedula = campoCedula.getText().trim();
        String correo = campoCorreo.getText().trim();
        String telefono = campoTelefono.getText().trim();
        String titulo = campoTitulo.getText().trim();
        String textoSueldo = campoSueldo.getText().trim();
        String nivel = String.valueOf(campoNivelDeFormacion.getSelectedItem());
        String area = String.valueOf(campoArea.getSelectedItem());

        if (nombres.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese los nombres del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese los apellidos del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese la cédula del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!cedula.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "La cédula debe tener 10 dígitos.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (correo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el correo electrónico del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (telefono.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el número de teléfono del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!telefono.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "El teléfono debe tener 10 dígitos, por ejemplo 0991234567.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (titulo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el título del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (campoArea.getSelectedIndex() < 1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione el área del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (textoSueldo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el sueldo del administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        float sueldo;
        try {
            sueldo = Float.parseFloat(textoSueldo);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El sueldo debe ser un número, por ejemplo 1200.50", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (sueldo <= 0) {
            JOptionPane.showMessageDialog(this, "El sueldo debe ser mayor a cero.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Administrativo nuevoAdministrativo = new Administrativo(cedula, nombres, apellidos, telefono, correo,
                sueldo, nivel, titulo, new ArrayList<>(), area);
        listaAdministrativos.add(nuevoAdministrativo);

        JOptionPane.showMessageDialog(this, "El administrativo se registró correctamente.", "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

        limpiarCampos();
    }//GEN-LAST:event_botonRegistrarActionPerformed

