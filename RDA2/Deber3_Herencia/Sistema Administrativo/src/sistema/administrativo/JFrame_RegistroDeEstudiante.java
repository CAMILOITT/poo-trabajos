        private void limpiarCampos() {
            campoNombres.setText("");
            campoApellidos.setText("");
            campoCedula.setText("");
            campoCorreo.setText("");
            campoTelefono.setText("");
            campoCarrera.setSelectedIndex(0);
            campoNivel.setSelectedIndex(0);
            mostrarCodigoGenerado();
        }

        private void mostrarCodigoGenerado() {
            campoCodigo.setText(SistemaAdministrativo.generarCodigoEstudiante(listaEstudiantes));
            campoCodigo.setEditable(false);
        }

