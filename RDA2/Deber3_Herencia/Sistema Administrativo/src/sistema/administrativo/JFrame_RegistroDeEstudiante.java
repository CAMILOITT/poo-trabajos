    private void botonRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonRegistrarActionPerformed
        // TODO add your handling code here:

        String nombres = campoNombres.getText().trim();
        String apellidos = campoApellidos.getText().trim();
        String cedula = campoCedula.getText().trim();
        String correo = campoCorreo.getText().trim();
        String telefono = campoTelefono.getText().trim();
        String carrera = String.valueOf(campoCarrera.getSelectedItem());
        String nivel = String.valueOf(campoNivel.getSelectedItem());
        String codigo = campoCodigo.getText().trim();

        if (nombres.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese los nombres del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese los apellidos del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!cedula.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "La cédula debe tener 10 dígitos.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (correo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingrese el correo electrónico del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!telefono.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "El teléfono debe tener 10 dígitos, por ejemplo 0991234567.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (campoCarrera.getSelectedIndex() < 1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione la carrera del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (campoNivel.getSelectedIndex() < 1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione el nivel del estudiante.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Estudiante nuevoEstudiante = new Estudiante(cedula, nombres, apellidos, telefono, correo, nivel, codigo, carrera);
        listaEstudiantes.add(nuevoEstudiante);

        JOptionPane.showMessageDialog(this, "El estudiante se registró correctamente.", "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

        limpiarCampos();
    }//GEN-LAST:event_botonRegistrarActionPerformed

