    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        if (campoCargo.getSelectedIndex() < 1) {
            JOptionPane.showMessageDialog(this, "Seleccione un cargo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String cargo = String.valueOf(campoCargo.getSelectedItem());
        ArrayList<Administrativo> administrativosEncontrados = SistemaAdministrativo.obtenerAdministrativosPorCargo(cargo, listaAdministrativos);

        campoTotalEncontrados.setText(String.valueOf(administrativosEncontrados.size()));
        actualizarTablaAdministrativos(administrativosEncontrados);

        if (administrativosEncontrados.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay administrativos con ese cargo.", "Aviso", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_botonBuscarActionPerformed

