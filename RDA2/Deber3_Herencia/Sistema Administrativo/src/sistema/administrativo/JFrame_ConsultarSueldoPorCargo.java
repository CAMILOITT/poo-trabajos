    private void cargarCargos() {
        campoCargo.addItem("Seleccione un cargo");
        for (int i = 0; i < listaDeCargos.size(); i++) {
            campoCargo.addItem(listaDeCargos.get(i));
        }
    }

    private void actualizarTablaAdministrativos(ArrayList<Administrativo> administrativosEncontrados) {
        DefaultTableModel modelo = (DefaultTableModel) tablaAdministrativos.getModel();
        modelo.setRowCount(0);

        for (int i = 0; i < administrativosEncontrados.size(); i++) {
            Administrativo administrativo = administrativosEncontrados.get(i);
            modelo.addRow(new Object[]{
                administrativo.getNombre() + " " + administrativo.getApellido(),
                administrativo.getArea(),
                String.format("$%.2f", administrativo.getSueldo())
            });
        }
    }

