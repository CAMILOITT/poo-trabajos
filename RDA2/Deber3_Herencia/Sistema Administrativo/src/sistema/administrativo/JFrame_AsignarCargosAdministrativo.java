    private void cargarAdministrativos() {
        comboAdministrativo.addItem("Seleccione un administrativo");
        for (int i = 0; i < listaAdministrativos.size(); i++) {
            comboAdministrativo.addItem(listaAdministrativos.get(i).getNombre() + " " + listaAdministrativos.get(i).getApellido());
        }
    }

    private void cargarCargos() {
        comboCargo.addItem("Seleccione un cargo");
        for (int i = 0; i < listaDeCargos.size(); i++) {
            comboCargo.addItem(listaDeCargos.get(i));
        }
    }

    private int obtenerAdministrativoSeleccionado() {
        return comboAdministrativo.getSelectedIndex() - 1;
    }

    private void actualizarTablaCargos() {
        DefaultTableModel modelo = (DefaultTableModel) tablaCargo.getModel();
        modelo.setRowCount(0);

        int posicionAdministrativo = obtenerAdministrativoSeleccionado();
        if (posicionAdministrativo == -1) {
            return;
        }

        ArrayList<String> cargosDelAdministrativo = listaAdministrativos.get(posicionAdministrativo).getListaDeCargos();
        for (int i = 0; i < cargosDelAdministrativo.size(); i++) {
            modelo.addRow(new Object[]{cargosDelAdministrativo.get(i)});
        }
    }

