    private void botonAniadirCargoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAniadirCargoActionPerformed
        // TODO add your handling code here:
        int posicionAdministrativo = obtenerAdministrativoSeleccionado();
        if (posicionAdministrativo == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un administrativo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (comboCargo.getSelectedIndex() < 1) {
            JOptionPane.showMessageDialog(this, "Seleccione un cargo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String cargo = String.valueOf(comboCargo.getSelectedItem());
        boolean cargoAgregado = listaAdministrativos.get(posicionAdministrativo).aniadirCargo(cargo);

        if (cargoAgregado) {
            actualizarTablaCargos();
        } else {
            JOptionPane.showMessageDialog(this, "El administrativo ya tiene ese cargo.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_botonAniadirCargoActionPerformed

