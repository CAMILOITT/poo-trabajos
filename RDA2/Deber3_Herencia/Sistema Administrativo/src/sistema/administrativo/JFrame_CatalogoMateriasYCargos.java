    private void botonAniadirMateriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAniadirMateriaActionPerformed
        // TODO add your handling code here:
        String nuevaMateria = campoNuevaMateria.getText().trim();

        if (nuevaMateria.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escriba el nombre de la materia.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (verificarExistencia(nuevaMateria, listaMaterias)) {
            JOptionPane.showMessageDialog(this, "Esa materia ya existe en el catálogo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        listaMaterias.add(nuevaMateria);
        actualizarTablaMaterias();
        campoNuevaMateria.setText("");
    }//GEN-LAST:event_botonAniadirMateriaActionPerformed

    private void botonAniadirCargoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAniadirCargoActionPerformed
        // TODO add your handling code here:
        String nuevoCargo = campoNuevoCargo.getText().trim();

        if (nuevoCargo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escriba el nombre del cargo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (verificarExistencia(nuevoCargo, listaDeCargos)) {
            JOptionPane.showMessageDialog(this, "Ese cargo ya existe en el catálogo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        listaDeCargos.add(nuevoCargo);
        actualizarTablaCargos();
        campoNuevoCargo.setText("");
    }//GEN-LAST:event_botonAniadirCargoActionPerformed

    private boolean verificarExistencia(String elemento, ArrayList<String> lista) {
        for (int i = 0; i < lista.size(); i++) {
            if (lista.get(i).equalsIgnoreCase(elemento)) {
                return true;
            }
        }
        return false;
    }

    private void actualizarTablaMaterias() {
        DefaultTableModel modelo = (DefaultTableModel) tablaMaterias.getModel();
        modelo.setRowCount(0);
        for (int i = 0; i < listaMaterias.size(); i++) {
            modelo.addRow(new Object[]{listaMaterias.get(i)});
        }
    }

    private void actualizarTablaCargos() {
        DefaultTableModel modelo = (DefaultTableModel) tablaCargo.getModel();
        modelo.setRowCount(0);
        for (int i = 0; i < listaDeCargos.size(); i++) {
            modelo.addRow(new Object[]{listaDeCargos.get(i)});
        }
    }
