    private void buttonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonGuardarActionPerformed
        String nom = txtNombre.getText().trim();
        String saludStr = txtSalud.getText().trim();
        String danioStr = txtDanio.getText().trim();
        String dropsStr = txtDrops.getText().trim();
        String espStr = txtEspecial.getText().trim();

        if (nom.isEmpty() || saludStr.isEmpty() || danioStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nombre, Salud y Danio son obligatorios.",
                    "Campos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        double salud, danio;
        try {
            salud = Double.parseDouble(saludStr);
            danio = Double.parseDouble(danioStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Salud y Danio deben ser numericos.",
                    "Error de formato", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this,
                "Se modificara el mob " + mob.getCodigo() + " - " + mob.getNombre()
                        + "\nConfirma la edicion?",
                "Confirmar edicion", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        ArrayList<String> drops = new ArrayList<>();
        if (!dropsStr.isEmpty()) {
            for (String d : dropsStr.split(",")) drops.add(d.trim());
        }
        mob.setNombre(nom);
        mob.setSaludMaxima(salud);
        mob.setDanioBase(danio);
        mob.setListaDrops(drops);

        if (mob instanceof Zombie) {
            ArrayList<String> vars = new ArrayList<>();
            if (!espStr.isEmpty()) {
                for (String v : espStr.split(",")) vars.add(v.trim());
            } else vars.add("Estandar");
            ((Zombie) mob).setVariante(vars);
        } else if (mob instanceof Esqueleto) {
            ((Esqueleto) mob).setTipoArco(espStr);
        } else if (mob instanceof Arania) {
            ((Arania) mob).setTipoVeneno(espStr);
        }

        JOptionPane.showMessageDialog(this, "Mob actualizado correctamente.",
                "Edicion confirmada", JOptionPane.INFORMATION_MESSAGE);
        if (alGuardar != null) alGuardar.run();
        this.dispose();
    }//GEN-LAST:event_buttonGuardarActionPerformed

