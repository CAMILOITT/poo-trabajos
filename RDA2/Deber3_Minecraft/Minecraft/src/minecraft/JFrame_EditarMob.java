    private String tipoDe() {
        if (mob instanceof Zombie) return "Zombie";
        if (mob instanceof Esqueleto) return "Esqueleto";
        if (mob instanceof Arania) return "Arania";
        return "Monstruo";
    }

    private String atributoEspecial() {
        if (mob instanceof Zombie) {
            ArrayList<String> v = ((Zombie) mob).getVariante();
            return v == null ? "" : String.join(", ", v);
        }
        if (mob instanceof Esqueleto) return ((Esqueleto) mob).getTipoArco();
        if (mob instanceof Arania) return ((Arania) mob).getTipoVeneno();
        return "";
    }

    private String imagenBody() {
        if (mob instanceof Zombie) return "/Incons/zombieBody.png";
        if (mob instanceof Esqueleto) return "/Incons/esqueletoBody.png";
        if (mob instanceof Arania) return "/Incons/araniaBody.png";
        return "/Incons/zombieBody.png";
    }

    private void cargarDatos() {
        txtCodigo.setText(mob.getCodigo());
        txtTipo.setText(tipoDe());
        txtNombre.setText(mob.getNombre());
        txtSalud.setText(String.valueOf(mob.getSaludMaxima()));
        txtDanio.setText(String.valueOf(mob.getDanioBase()));
        txtDrops.setText(mob.getListaDrops() == null ? "" : String.join(", ", mob.getListaDrops()));
        txtEspecial.setText(atributoEspecial());
        if (mob instanceof Esqueleto) lblEspecial.setText("Tipo Arco:");
        else if (mob instanceof Arania) lblEspecial.setText("Tipo Veneno:");
        else lblEspecial.setText("Variante (coma):");
        try {
            Image img = new ImageIcon(getClass().getResource(imagenBody())).getImage()
                    .getScaledInstance(220, 320, Image.SCALE_SMOOTH);
            lblImagen.setIcon(new ImageIcon(img));
            lblImagen.setText("");
        } catch (Exception ex) {
            lblImagen.setText(tipoDe());
        }
    }

