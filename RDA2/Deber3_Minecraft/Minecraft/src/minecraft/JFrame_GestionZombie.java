    private void buttonBuscarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_buttonBuscarActionPerformed
        // TODO add your handling code here:
        String codigoBuscado = IngresoBuscar.getText().trim();

        if (codigoBuscado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingresa un código en la casilla superior para realizar la búsqueda.",
                    "Campo Vacío",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean encontrado = false;

        for (Zombie z : listaZombies) {
            if (z.getCodigo().equalsIgnoreCase(codigoBuscado)) {
                encontrado = true;
                zombieCargado = z; // Guardamos la referencia para poder editar después

                // Cargamos los datos en tus componentes renombrados
                nombre.setText(z.getNombre());
                saludMaxima.setText(String.valueOf(z.getSaludMaxima()));
                DanioBase.setText(String.valueOf(z.getDanioBase()));

                // Cargamos variante/tipo
                if (z.getVariante() != null && !z.getVariante().isEmpty()) {
                    tipo.setText(String.join(", ", z.getVariante()));
                } else {
                    tipo.setText("Estándar");
                }

                // Cargamos drops
                if (z.getListaDrops() != null) {
                    Drop.setText(String.join(", ", z.getListaDrops()));
                } else {
                    Drop.setText("");
                }

                javax.swing.JOptionPane.showMessageDialog(this,
                        "Zombie encontrado. Datos cargados en el formulario.",
                        "Búsqueda Exitosa",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);
                break;
            }
        }

        if (!encontrado) {
            zombieCargado = null;

            // Limpiamos el formulario si no existe
            nombre.setText("");
            saludMaxima.setText("");
            DanioBase.setText("");
            tipo.setText("");
            Drop.setText("");

            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se encontró ningún Zombie con el código: " + codigoBuscado
                            + "\nPuedes llenar las casillas y presionar 'Agregar' para registrar uno nuevo.",
                    "Sin Coincidencias",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }// GEN-LAST:event_buttonBuscarActionPerformed

