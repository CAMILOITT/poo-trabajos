    private void configurarAutocompletado() {
    campoCedula.setModel(new DefaultComboBoxModel<>());   // quita "Item 1, Item 2..."
    campoCedula.setEditable(true);

    final JTextField editor = (JTextField) campoCedula.getEditor().getEditorComponent();

    editor.addKeyListener(new KeyAdapter() {
        @Override
        public void keyReleased(KeyEvent e) {
            int tecla = e.getKeyCode();
            if (tecla == KeyEvent.VK_UP || tecla == KeyEvent.VK_DOWN
                    || tecla == KeyEvent.VK_ENTER || tecla == KeyEvent.VK_ESCAPE) {
                return;   // dejar que las flechas y Enter funcionen normal
            }

            String texto = editor.getText();
            DefaultComboBoxModel<String> modelo = new DefaultComboBoxModel<>();

            for (Cliente c : listaClientes) {
                if (c.getCedula().startsWith(texto)) {
                    modelo.addElement(c.getCedula());
                }
            }

            campoCedula.setModel(modelo);
            editor.setText(texto);   // setModel borra lo escrito, hay que restaurarlo
            campoCedula.setPopupVisible(modelo.getSize() > 0 && !texto.isEmpty());
        }
    });
}
    
