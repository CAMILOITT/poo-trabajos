    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        String cedula = String.valueOf(campoCedula.getEditor().getItem()).trim();
        Cliente encontrado = null;
        
        for (Cliente c: listaClientes)
        {
            if (c.getCedula().equals(cedula))
            {
                encontrado = c;
                break;
            }
        }
        
        if (encontrado == null)
        {
            JOptionPane.showMessageDialog(this, "Cliente no encontrado.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        campoNombre.setText(encontrado.getNombre() + " " + encontrado.getApellido());
        campoCelular.setText(encontrado.getTelefono());
        campoCorreoElectronico.setText(encontrado.getCorreo());
        campoPuntos.setText("" + encontrado.getPuntos());
        
        DefaultListModel<String> modelo = new DefaultListModel<>();
        
        for (Compra compra: encontrado.getListaDeCompras())
        {
            for (Producto p: compra.getListaDeProductosComprados())
            {
                modelo.addElement(p.getNombreProducto());
            }
        }
        listaProductos.setModel(modelo);
    }//GEN-LAST:event_botonBuscarActionPerformed

