    private void cargarClientes() {
    comboCliente.removeAllItems();
    comboCliente.addItem("Seleccione un cliente");
    for (int i = 0; i < listaClientes.size(); i++) {
        Cliente c = listaClientes.get(i);
        comboCliente.addItem(c.getNombre() + " " + c.getApellido() + " - " + c.getCedula());
    }
    }

    private void generarNumeroYFecha() {
        campoNumero.setText(String.format("F-%03d", listaFacturas.size() + 1));
        campoFecha.setText(new SimpleDateFormat("dd/MM/yyyy").format(new Date()));
    }

    private boolean estaFacturada(OrdenTrabajo orden) {
        for (int i = 0; i < listaFacturas.size(); i++) {
            if (listaFacturas.get(i).getListaDeOrdenes().contains(orden)) {
                return true;
            }
        }
        return false;
    }

    private void cargarOrdenesPendientes() {
        if (listaClientes == null || listaFacturas == null) {
            return;
        }

        ordenesPendientes.clear();
        int posicion = comboCliente.getSelectedIndex();

        if (posicion > 0) {
            Cliente cliente = listaClientes.get(posicion - 1);
            for (int i = 0; i < cliente.getOrdenesRealizadas().size(); i++) {
                OrdenTrabajo orden = cliente.getOrdenesRealizadas().get(i);
                if (!estaFacturada(orden)) {
                    ordenesPendientes.add(orden);
                }
            }
        }

        actualizarTablaOrdenes();
    }

    private void actualizarTablaOrdenes() {
        DefaultTableModel modelo = (DefaultTableModel) tablaOrdenes.getModel();
        modelo.setRowCount(0);
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");

        for (int i = 0; i < ordenesPendientes.size(); i++) {
            OrdenTrabajo o = ordenesPendientes.get(i);
            modelo.addRow(new Object[] {
                o.getNumeroOrden(),
                formato.format(o.getFecha()),
                String.format("%.2f", o.calcularSubtotal())
            });
        }
    }

    private void limpiarFormulario() {
        comboCliente.setSelectedIndex(0);
        areaFactura.setText("");
        cargarOrdenesPendientes();
        generarNumeroYFecha();
    }
    
