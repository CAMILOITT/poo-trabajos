    private void botonGenerarFacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGenerarFacturaActionPerformed
        // TODO add your handling code here:
        int posCliente = comboCliente.getSelectedIndex();
    if (posCliente <= 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un cliente.",
            "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int[] filas = tablaOrdenes.getSelectedRows();
    if (filas.length == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione al menos una orden de la tabla.",
            "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }

    ArrayList<OrdenTrabajo> seleccionadas = new ArrayList<>();
    for (int i = 0; i < filas.length; i++) {
        seleccionadas.add(ordenesPendientes.get(filas[i]));
    }

    Cliente cliente = listaClientes.get(posCliente - 1);
    Factura factura = new Factura(listaFacturas.size() + 1, new Date(), seleccionadas);
    listaFacturas.add(factura);
    ArchivoDatos.guardarFactura(factura);

    areaFactura.setText("Cliente: " + cliente.getNombre() + " " + cliente.getApellido()
        + " - " + cliente.getCedula() + "\n\n" + factura.imprimirFactura());

    JOptionPane.showMessageDialog(this,
        String.format("Factura F-%03d generada. Total: $ %.2f", factura.getNumeroFactura(), factura.getTotal()),
        "Factura creada", JOptionPane.INFORMATION_MESSAGE);

    generarNumeroYFecha();
    cargarOrdenesPendientes();
        
    }//GEN-LAST:event_botonGenerarFacturaActionPerformed

