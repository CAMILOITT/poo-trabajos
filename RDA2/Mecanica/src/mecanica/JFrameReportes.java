    private void mostrarGrafico(JFreeChart grafico) {
        panelGrafico.removeAll();
        panelGrafico.add(new ChartPanel(grafico), java.awt.BorderLayout.CENTER);
        panelGrafico.revalidate();
        panelGrafico.repaint();
    }

    private void graficarOrdenesPorMecanico() {
        DefaultCategoryDataset datos = new DefaultCategoryDataset();
        int totalOrdenes = 0;
        int maximo = 0;

        for (Mecanico m : listaMecanicos) {
            int cantidad = 0;
            if (m.getOrdenRegistrada() != null) {
                cantidad = m.getOrdenRegistrada().size();
            }
            datos.addValue(cantidad, "Órdenes", m.getNombre() + " " + m.getApellido());
            totalOrdenes += cantidad;
            if (cantidad > maximo) {
                maximo = cantidad;
            }
        }

        JFreeChart grafico = ChartFactory.createBarChart(
                "Órdenes de trabajo por mecánico", "Mecánico", "Número de órdenes", datos);
        org.jfree.chart.axis.NumberAxis eje = (org.jfree.chart.axis.NumberAxis) grafico.getCategoryPlot().getRangeAxis();
        eje.setStandardTickUnits(org.jfree.chart.axis.NumberAxis.createIntegerTickUnits());
        eje.setRange(0, Math.max(5, maximo + 1));
        BarRenderer dibujoBarras = (BarRenderer) grafico.getCategoryPlot().getRenderer();
        dibujoBarras.setBarPainter(new StandardBarPainter());
        dibujoBarras.setSeriesPaint(0, new Color(0, 102, 153));
        mostrarGrafico(grafico);
        etiquetaResumen.setText("Total de órdenes registradas: " + totalOrdenes);
    }

    private void graficarStockRepuestos() {
        DefaultCategoryDataset datos = new DefaultCategoryDataset();
        int pocoStock = 0;

        for (Repuesto r : listaRepuestos) {
            datos.addValue(r.getCantidad(), "Unidades", r.getNombre());
            if (r.getCantidad() < 5) {
                pocoStock++;
            }
        }

        JFreeChart grafico = ChartFactory.createBarChart(
                "Stock de repuestos", "Repuesto", "Unidades disponibles", datos);
        org.jfree.chart.axis.NumberAxis eje = (org.jfree.chart.axis.NumberAxis) grafico.getCategoryPlot().getRangeAxis();
        eje.setStandardTickUnits(org.jfree.chart.axis.NumberAxis.createIntegerTickUnits());
        org.jfree.chart.axis.CategoryAxis ejeRepuestos = grafico.getCategoryPlot().getDomainAxis();
        ejeRepuestos.setCategoryLabelPositions(org.jfree.chart.axis.CategoryLabelPositions.UP_45);
        BarRenderer dibujoBarras = (BarRenderer) grafico.getCategoryPlot().getRenderer();
        dibujoBarras.setBarPainter(new StandardBarPainter());
        dibujoBarras.setSeriesPaint(0, new Color(0, 102, 153));
        mostrarGrafico(grafico);
        etiquetaResumen.setText("Repuestos con menos de 5 unidades: " + pocoStock);
    }

