    private void cargarDocentes() {
        ConexionAcademico conexionAcademico = new ConexionAcademico();
        Connection conexion = conexionAcademico.abrirConexion();
        if (conexion == null) {
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) jTableResul.getModel();
        modelo.setRowCount(0);
        try {
            Statement sentencia = conexion.createStatement();

            ResultSet resultado = sentencia.executeQuery("SELECT\n" +
            "    d.codigo_docente,\n" +
            "    d.cedula,\n" +
            "    d.nombre,\n" +
            "    d.apellido\n" +
            "FROM\n" +
            "    DOCENTE AS d,\n" +
            "    CARRERA AS c\n" +
            "WHERE\n" +
            "    d.codigo_carrera = c.codigo_carrera\n" +
            "    AND c.nombre = '"+ cmbCarreras.getSelectedItem().toString()+"';");

            while(resultado.next())
            {
                String codigo = resultado.getString(1);
                String Cedula = resultado.getString(2);
                String nombre = resultado.getString(3);
                String apellido = resultado.getString(4);

                String[] fila = new String[3];
                fila[0] = codigo;
                fila[1] = Cedula;
                fila[2] = nombre + " " + apellido;

                modelo.addRow(fila);
            }

            resultado.close();
            sentencia.close();
            conexion.close();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar los docentes " + e.getMessage());
        }
    }

