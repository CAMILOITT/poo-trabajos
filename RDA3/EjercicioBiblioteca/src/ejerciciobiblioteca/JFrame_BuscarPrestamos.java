    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        DefaultTableModel modelo = (DefaultTableModel) tablaLibros.getModel();
        modelo.setRowCount(0);
        etiquetaResultado.setText(" ");

        String NombreCliente = CampoNombreCliente.getText().trim();
        String Cedula = CampoCedula.getText().trim();

        // 1. Se busca con el campo que el usuario lleno
        boolean porCedula = !Cedula.isEmpty();

        if (Cedula.isEmpty() && NombreCliente.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Escriba la cédula o el nombre del socio.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            CampoCedula.requestFocus();
            return;
        }
        if (porCedula && !validarCedula(Cedula))
        {
            JOptionPane.showMessageDialog(this, "La cédula debe tener 10 dígitos numéricos.", "Cédula no válida", JOptionPane.ERROR_MESSAGE);
            CampoCedula.requestFocus();
            return;
        }

        try
        {
            String Nombre;
            String Titulo;
            String id_prestamo;
            String Estado;
            String Fecha;

            Connection conexion = DriverManager.getConnection(
                "jdbc:ucanaccess://C:/Users/mnobo/OneDrive/Documentos/Universidad PUCE/puce/cuarto semestre/Programación III POO/poo-trabajos2/poo-trabajos/RDA3/EjercicioBiblioteca/BIBLIOTECA.accdb");
            System.out.println("Conexion exitosa");
            Statement st = conexion.createStatement();

            // 2. Buscar al socio por cedula o por nombre
            ResultSet socios;
            if (porCedula)
            {
                socios = st.executeQuery("SELECT codigo_id, nombre, apellido, cedula FROM SOCIO WHERE cedula = '" + Cedula + "'");
            }
            else
            {
                socios = st.executeQuery("SELECT codigo_id, nombre, apellido, cedula FROM SOCIO");
            }

            String CodigoSocio = "";
            String NombreSocio = "";
            String CedulaSocio = "";
            int encontrados = 0;

            while (socios.next())
            {
                String nombreCompleto = socios.getString(2) + " " + socios.getString(3);

                // por nombre vale el nombre solo o el nombre con apellido
                if (porCedula || nombreCompleto.equalsIgnoreCase(NombreCliente)
                        || socios.getString(2).equalsIgnoreCase(NombreCliente))
                {
                    encontrados++;
                    CodigoSocio = socios.getString(1);
                    NombreSocio = nombreCompleto;
                    CedulaSocio = socios.getString(4);
                }
            }

            if (encontrados == 0)
            {
                conexion.close();
                JOptionPane.showMessageDialog(this, "No existe un socio con ese dato.", "Socio no encontrado", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            if (encontrados > 1)
            {
                conexion.close();
                JOptionPane.showMessageDialog(this, "Hay varios socios con ese nombre.\nEscriba nombre y apellido o busque por cédula.", "Varios socios", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // se muestra el dato que no se escribio
            CampoNombreCliente.setText(NombreSocio);
            CampoCedula.setText(CedulaSocio);

            // 3. Prestamos del socio con sus libros
            ResultSet resultado = st.executeQuery(
                    "SELECT\n" +
                    "    p.id_prestamo,\n" +
                    "    l.titulo,\n" +
                    "    a.nombre,\n" +
                    "    a.apellido,\n" +
                    "    p.estado,\n" +
                    "    p.fecha_prestamo\n" +
                    "FROM\n" +
                    "    PRESTAMO p,\n" +
                    "    AUTOR a,\n" +
                    "    LIBRO l,\n" +
                    "    DETALLE_PRESTAMO d\n" +
                    "WHERE\n" +
                    "    p.codigo_socio = '" + CodigoSocio + "'\n" +
                    "    AND d.id_prestamo = p.id_prestamo\n" +
                    "    AND l.id_libro = d.id_libro\n" +
                    "    AND a.codigo_id = l.codigo_autor\n" +
                    "ORDER BY p.id_prestamo"
                );

            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");

            while (resultado.next())
            {
                id_prestamo = resultado.getString(1);
                Titulo = resultado.getString(2);
                Nombre = resultado.getString(3) + " "+ resultado.getString(4);
                Estado = resultado.getString(5);
                Fecha = formato.format(resultado.getDate(6));

                String[] fila = new String[5];
                fila[0] = id_prestamo;
                fila[1] = Titulo;
                fila[2] = Nombre;
                fila[3] = Estado;
                fila[4] = Fecha;

                modelo.addRow(fila);
            }
            conexion.close();

            if (modelo.getRowCount() == 0)
            {
                JOptionPane.showMessageDialog(this, NombreSocio + " no tiene préstamos registrados.", "Sin préstamos", JOptionPane.INFORMATION_MESSAGE);
            }
            else
            {
                etiquetaResultado.setText("Préstamos de " + NombreSocio + ": " + modelo.getRowCount() + " libros");
            }
        }
        catch (SQLException e)
        {
            System.out.println("No se pudo conectar: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "No se pudo conectar con la base de datos", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonBuscarActionPerformed

    // la cedula es valida si tiene 10 digitos
    private boolean validarCedula(String cedula)
    {
        return cedula.matches("\\d{10}");
    }

