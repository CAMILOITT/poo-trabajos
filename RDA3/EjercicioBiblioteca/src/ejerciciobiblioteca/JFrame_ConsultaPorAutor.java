    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
        // TODO add your handling code here:
        DefaultTableModel modelo = (DefaultTableModel) tablaLibros.getModel();
        modelo.setRowCount(0);
        etiquetaResultado.setText(" ");

        int anio1 = Integer.parseInt((String) jComboAnio1.getSelectedItem());
        int anio2 = Integer.parseInt((String) jComboAnio2.getSelectedItem());

        // se valida antes de abrir la conexion
        if (anio1 > anio2)
        {
            JOptionPane.showMessageDialog(this, "El anio 1 debe ser menor o igual al anio 2", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try
        {
            String Nombre; 
            String Titulo;
            String id_libro;
            int anio_publicacion;
            
            Connection conexion = DriverManager.getConnection(
                "jdbc:ucanaccess://C:/Users/mnobo/OneDrive/Documentos/Universidad PUCE/puce/cuarto semestre/Programación III POO/poo-trabajos2/poo-trabajos/RDA3/EjercicioBiblioteca/BIBLIOTECA.accdb");
            System.out.println("Conexion exitosa");
            Statement st = conexion.createStatement();
            
            // >= y <= para que tambien entren los libros de los anios elegidos
            ResultSet resultado = st.executeQuery(
            "Select a.nombre, a.apellido, l.titulo, l.id_libro, l.anio_publicacion from LIBRO l, AUTOR a where a.codigo_id = l.codigo_autor and l.anio_publicacion >= " + anio1+ " and l.anio_publicacion <= " + anio2+ " order by l.anio_publicacion;"
            );
            
            while (resultado.next())
            {
                
                Nombre = resultado.getString(1) + " "+ resultado.getString(2);
                Titulo = resultado.getString(3);
                id_libro = resultado.getString(4);
                anio_publicacion = resultado.getInt(5);            

                String[] fila = new String[4];
                fila[0] = id_libro;
                fila[1] = Titulo;
                fila[2] = Nombre;
                fila[3] = Integer.toString(anio_publicacion);

                modelo.addRow(fila);
            }
            conexion.close();

            if (modelo.getRowCount() == 0)
            {
                JOptionPane.showMessageDialog(this, "No hay libros publicados entre " + anio1 + " y " + anio2, "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
            }
            else
            {
                etiquetaResultado.setText("Se encontraron " + modelo.getRowCount() + " libros entre " + anio1 + " y " + anio2);
            }
        }
        catch (SQLException e)
        {
            System.out.println("No se pudo conectar: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "No se pudo conectar con la base de datos", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_botonBuscarActionPerformed



